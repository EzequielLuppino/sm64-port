static inline u32 gfx_3ds_rgb_to_abgr(u32 rgb)
{
    // 0xRRGGBB to 0xFFBBGGRR
    return (0x0000ff & (rgb >> 16))
        | (0x00ff00 & rgb)
        | (0xff0000 & (rgb << 16))
        | 0xff000000;
}

